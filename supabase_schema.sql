-- 9. TRANSACTIONAL PURCHASE RPC FUNCTION (create_agromart_purchase)
CREATE OR REPLACE FUNCTION create_agromart_purchase(
    p_supplier_id BIGINT,
    p_supplier_name TEXT,
    p_supplier_mobile TEXT,
    p_discount_amount NUMERIC,
    p_paid_amount NUMERIC,
    p_cash_amount NUMERIC,
    p_upi_amount NUMERIC,
    p_bank_amount NUMERIC,
    p_payment_method TEXT,
    p_notes TEXT,
    p_items JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_user_id UUID;
    v_purchase_num TEXT;
    v_year INT;
    v_purchase_id BIGINT;
    v_supplier suppliers%ROWTYPE;
    v_item JSONB;
    v_product_id BIGINT;
    v_requested_qty INT;
    v_purchase_rate NUMERIC;
    v_item_disc NUMERIC;
    v_gst_pct NUMERIC;
    v_batch_no TEXT;
    v_mfg_date DATE;
    v_expiry_date DATE;
    
    v_gross_subtotal NUMERIC := 0.0;
    v_gst_total NUMERIC := 0.0;
    v_grand_total NUMERIC := 0.0;
    v_total_paid NUMERIC := 0.0;
    v_pending NUMERIC := 0.0;
    v_payment_status TEXT;
    
    v_product products%ROWTYPE;
    v_batch_id BIGINT;
    v_item_gross NUMERIC;
    v_item_taxable NUMERIC;
    v_item_gst NUMERIC;
    v_item_total NUMERIC;
    v_pay_no TEXT;
BEGIN
    -- A. AUTHENTICATION CHECK
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Authentication required to create a purchase record.';
    END IF;

    -- B. PAYLOAD VALIDATION
    IF p_items IS NULL OR jsonb_array_length(p_items) = 0 THEN
        RAISE EXCEPTION 'Cannot create empty purchase. Please add at least one product item.';
    END IF;

    IF COALESCE(p_paid_amount, 0) < 0 THEN
        RAISE EXCEPTION 'Paid amount cannot be negative.';
    END IF;

    v_total_paid := ROUND(COALESCE(p_paid_amount, 0.0), 2);

    -- C. CONCURRENCY-SAFE PURCHASE NUMBER GENERATION
    v_year := EXTRACT(YEAR FROM NOW());
    v_purchase_num := 'PUR-' || v_year || '-' || LPAD(nextval('purchase_number_seq')::TEXT, 5, '0');

    -- D. VALIDATE SUPPLIER IF SPECIFIED
    IF p_supplier_id IS NOT NULL THEN
        SELECT * INTO v_supplier FROM suppliers WHERE id = p_supplier_id FOR UPDATE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Supplier ID % not found', p_supplier_id;
        END IF;
    END IF;

    -- E. PRE-PASS: VALIDATE PRODUCTS, QUANTITIES, PRICES & DATES
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        v_product_id := (v_item->>'product_id')::BIGINT;
        v_requested_qty := (v_item->>'quantity')::INT;
        v_purchase_rate := ROUND(COALESCE((v_item->>'purchase_price')::NUMERIC, (v_item->>'purchase_rate')::NUMERIC, 0.0), 2);
        v_gst_pct := COALESCE((v_item->>'gst_percent')::NUMERIC, (v_item->>'gst_rate')::NUMERIC, 5.0);
        v_item_disc := ROUND(COALESCE((v_item->>'discount')::NUMERIC, (v_item->>'item_discount')::NUMERIC, 0.0), 2);
        v_mfg_date := CASE WHEN (v_item->>'manufacturing_date') IS NOT NULL AND (v_item->>'manufacturing_date') != '' THEN (v_item->>'manufacturing_date')::DATE ELSE NULL END;
        v_expiry_date := CASE WHEN (v_item->>'expiry_date') IS NOT NULL AND (v_item->>'expiry_date') != '' THEN (v_item->>'expiry_date')::DATE ELSE NULL END;

        IF v_requested_qty IS NULL OR v_requested_qty <= 0 THEN
            RAISE EXCEPTION 'Purchase quantity must be greater than zero for product ID %', v_product_id;
        END IF;

        IF v_purchase_rate < 0 THEN
            RAISE EXCEPTION 'Purchase price cannot be negative for product ID %', v_product_id;
        END IF;

        IF v_gst_pct < 0 OR v_gst_pct > 100 THEN
            RAISE EXCEPTION 'GST percent must be between 0 and 100 for product ID %', v_product_id;
        END IF;

        SELECT * INTO v_product FROM products WHERE id = v_product_id FOR UPDATE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Product ID % not found', v_product_id;
        END IF;

        v_item_gross := v_requested_qty * v_purchase_rate;
        IF v_item_disc > v_item_gross THEN
            RAISE EXCEPTION 'Item discount (₹%) cannot exceed line total (₹%) for product %', v_item_disc, v_item_gross, v_product.name;
        END IF;

        IF v_expiry_date IS NOT NULL AND v_expiry_date < CURRENT_DATE THEN
            RAISE EXCEPTION 'Expiry date (%) cannot be in the past for product %', v_expiry_date, v_product.name;
        END IF;

        IF v_mfg_date IS NOT NULL AND v_expiry_date IS NOT NULL AND v_mfg_date > v_expiry_date THEN
            RAISE EXCEPTION 'Manufacturing date (%) cannot be after expiry date (%) for product %', v_mfg_date, v_expiry_date, v_product.name;
        END IF;

        v_item_taxable := v_item_gross - v_item_disc;
        v_item_gst := ROUND(v_item_taxable * (v_gst_pct / 100.0), 2);
        v_item_total := v_item_taxable + v_item_gst;

        v_gross_subtotal := v_gross_subtotal + v_item_taxable;
        v_gst_total := v_gst_total + v_item_gst;
        v_grand_total := v_grand_total + v_item_total;
    END LOOP;

    IF v_total_paid > v_grand_total THEN
        RAISE EXCEPTION 'Paid amount (₹%) cannot exceed purchase grand total (₹%).', v_total_paid, v_grand_total;
    END IF;

    v_pending := GREATEST(0.0, v_grand_total - v_total_paid);

    v_payment_status := CASE 
        WHEN v_total_paid >= v_grand_total THEN 'Paid'
        WHEN v_total_paid > 0 THEN 'Partially Paid'
        ELSE 'Pending'
    END;

    -- F. CREATE PURCHASE HEADER
    INSERT INTO purchases (
        purchase_number, supplier_id, supplier_name,
        subtotal, gst_amount, grand_total, paid_amount, pending_amount,
        payment_status, notes, created_at
    ) VALUES (
        v_purchase_num, p_supplier_id, COALESCE(v_supplier.name, p_supplier_name, 'Unknown Supplier'),
        v_gross_subtotal, v_gst_total, v_grand_total, v_total_paid, v_pending,
        v_payment_status, p_notes, NOW()
    ) RETURNING id INTO v_purchase_id;

    -- G. PROCESS BATCHES, STOCK MOVEMENT & PURCHASE ITEMS
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        v_product_id := (v_item->>'product_id')::BIGINT;
        v_requested_qty := (v_item->>'quantity')::INT;
        v_purchase_rate := ROUND(COALESCE((v_item->>'purchase_price')::NUMERIC, (v_item->>'purchase_rate')::NUMERIC, 0.0), 2);
        v_gst_pct := COALESCE((v_item->>'gst_percent')::NUMERIC, (v_item->>'gst_rate')::NUMERIC, 5.0);
        v_item_disc := ROUND(COALESCE((v_item->>'discount')::NUMERIC, (v_item->>'item_discount')::NUMERIC, 0.0), 2);
        v_batch_no := COALESCE(v_item->>'batch_number', 'BT-' || EXTRACT(EPOCH FROM NOW())::INT);
        v_mfg_date := CASE WHEN (v_item->>'manufacturing_date') IS NOT NULL AND (v_item->>'manufacturing_date') != '' THEN (v_item->>'manufacturing_date')::DATE ELSE NULL END;
        v_expiry_date := CASE WHEN (v_item->>'expiry_date') IS NOT NULL AND (v_item->>'expiry_date') != '' THEN (v_item->>'expiry_date')::DATE ELSE NULL END;

        SELECT * INTO v_product FROM products WHERE id = v_product_id;

        v_item_gross := v_requested_qty * v_purchase_rate;
        v_item_taxable := v_item_gross - v_item_disc;
        v_item_gst := ROUND(v_item_taxable * (v_gst_pct / 100.0), 2);
        v_item_total := v_item_taxable + v_item_gst;

        -- Create or update batch (Upsert on unique_product_batch)
        SELECT id INTO v_batch_id FROM product_batches WHERE product_id = v_product_id AND batch_number = v_batch_no;

        IF v_batch_id IS NOT NULL THEN
            UPDATE product_batches SET
                current_quantity = current_quantity + v_requested_qty,
                purchase_price = v_purchase_rate
            WHERE id = v_batch_id;
        ELSE
            INSERT INTO product_batches (
                product_id, supplier_id, batch_number, mfg_date, expiry_date,
                initial_quantity, current_quantity, purchase_price, selling_price
            ) VALUES (
                v_product_id, p_supplier_id, v_batch_no, v_mfg_date, v_expiry_date,
                v_requested_qty, v_requested_qty, v_purchase_rate, v_product.selling_price
            ) RETURNING id INTO v_batch_id;
        END IF;

        -- Record Purchase Item
        INSERT INTO purchase_items (
            purchase_id, product_id, batch_id, quantity, purchase_price, gst_percent,
            taxable_amount, gst_amount, total_amount
        ) VALUES (
            v_purchase_id, v_product_id, v_batch_id, v_requested_qty, v_purchase_rate, v_gst_pct,
            v_item_taxable, v_item_gst, v_item_total
        );

        -- Record Stock Movement Log (PURCHASE)
        INSERT INTO stock_movements (
            product_id, batch_id, movement_type, quantity, reference_type, reference_id, notes
        ) VALUES (
            v_product_id, v_batch_id, 'PURCHASE', v_requested_qty, 'PURCHASE', v_purchase_num, 'Purchase Order ' || v_purchase_num
        );

        -- Update product purchase_price (Latest Purchase Price) and total_stock summary
        UPDATE products SET
            purchase_price = v_purchase_rate,
            total_stock = (
                SELECT COALESCE(SUM(current_quantity), 0)
                FROM product_batches
                WHERE product_id = v_product_id
                  AND (expiry_date IS NULL OR expiry_date >= CURRENT_DATE)
            )
        WHERE id = v_product_id;
    END LOOP;

    -- H. PAYMENTS & SUPPLIER PAYABLE UPDATE
    IF v_total_paid > 0 THEN
        v_pay_no := 'PAY-SUP-' || v_year || '-' || LPAD(nextval('payment_number_seq')::TEXT, 5, '0');
        INSERT INTO payments (payment_number, supplier_id, purchase_id, payment_type, amount, payment_method, notes)
        VALUES (v_pay_no, p_supplier_id, v_purchase_id, 'SUPPLIER_PAYMENT', v_total_paid, COALESCE(p_payment_method, 'Bank Transfer'), 'Payment for Purchase ' || v_purchase_num);
    END IF;

    IF p_supplier_id IS NOT NULL THEN
        UPDATE suppliers SET
            total_purchases = COALESCE(total_purchases, 0.0) + v_grand_total,
            pending_payment = COALESCE(pending_payment, 0.0) + v_pending,
            pending_payable = COALESCE(pending_payable, 0.0) + v_pending
        WHERE id = p_supplier_id;
    END IF;

    RETURN jsonb_build_object(
        'id', v_purchase_id,
        'purchase_number', v_purchase_num,
        'grand_total', v_grand_total,
        'paid_amount', v_total_paid,
        'pending_amount', v_pending,
        'payment_status', v_payment_status
    );
END;
$$;

