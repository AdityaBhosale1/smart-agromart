-- 8. TRANSACTIONAL BILLING RPC FUNCTION (create_agromart_bill)
-- Hardened: Proportional Pre-Tax Invoice Discount over Net Subtotal with Residual Handling, Separate CGST/SGST Accumulators, Strict Payment & Null-Safe Farmer Credit
CREATE OR REPLACE FUNCTION create_agromart_bill(
    p_farmer_id BIGINT,
    p_farmer_name TEXT,
    p_farmer_mobile TEXT,
    p_discount_amount NUMERIC,
    p_paid_amount NUMERIC,
    p_cash_amount NUMERIC,
    p_upi_amount NUMERIC,
    p_payment_method TEXT,
    p_due_date TIMESTAMPTZ,
    p_notes TEXT,
    p_items JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_user_id UUID;
    v_invoice_num TEXT;
    v_year INT;
    v_bill_id BIGINT;
    v_farmer farmers%ROWTYPE;
    v_farmer_pending NUMERIC := 0.0;
    v_farmer_limit NUMERIC := 50000.0;
    v_item JSONB;
    v_product_id BIGINT;
    v_requested_qty INT;
    v_unit_price NUMERIC;
    v_item_disc NUMERIC;
    v_gross_subtotal NUMERIC := 0.0;
    v_total_item_discounts NUMERIC := 0.0;
    v_net_before_inv_disc_subtotal NUMERIC := 0.0;
    v_inv_discount NUMERIC := 0.0;
    v_inv_disc_rem NUMERIC := 0.0;
    v_net_rem NUMERIC := 0.0;
    v_product products%ROWTYPE;
    v_batch product_batches%ROWTYPE;
    v_available_stock INT;
    v_alloc_qty INT;
    v_rem_qty INT;
    
    -- Exact accumulators from rounded bill_items
    v_item_discounts_total NUMERIC := 0.0;
    v_inv_discounts_total NUMERIC := 0.0;
    v_taxable_subtotal NUMERIC := 0.0;
    v_cgst_total NUMERIC := 0.0;
    v_sgst_total NUMERIC := 0.0;
    v_gst_total NUMERIC := 0.0;
    v_grand_total NUMERIC := 0.0;
    v_pending NUMERIC := 0.0;
    v_total_paid NUMERIC := 0.0;
    v_cash_paid NUMERIC := 0.0;
    v_upi_paid NUMERIC := 0.0;
    v_payment_status TEXT;
    
    -- Line item & batch variables
    v_item_gross NUMERIC;
    v_item_disc_rem NUMERIC;
    v_item_qty_rem INT;
    v_item_disc_alloc NUMERIC;
    v_item_net_before_inv NUMERIC;
    v_inv_disc_share NUMERIC;
    v_alloc_taxable NUMERIC;
    v_alloc_gst NUMERIC;
    v_alloc_cgst NUMERIC;
    v_alloc_sgst NUMERIC;
    v_alloc_total NUMERIC;
    v_pay_no TEXT;
BEGIN
    -- A. AUTHENTICATION CHECK
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Authentication required to create a bill';
    END IF;

    -- B. PAYLOAD & FINANCIAL VALIDATION
    IF p_items IS NULL OR jsonb_array_length(p_items) = 0 THEN
        RAISE EXCEPTION 'Cannot generate empty bill. Please add at least one item.';
    END IF;

    v_inv_discount := ROUND(COALESCE(p_discount_amount, 0.0), 2);
    IF v_inv_discount < 0 THEN
        RAISE EXCEPTION 'Invoice discount amount cannot be negative.';
    END IF;

    v_cash_paid := ROUND(COALESCE(p_cash_amount, 0.0), 2);
    v_upi_paid := ROUND(COALESCE(p_upi_amount, 0.0), 2);

    IF COALESCE(p_paid_amount, 0) < 0 OR v_cash_paid < 0 OR v_upi_paid < 0 THEN
        RAISE EXCEPTION 'Payment amounts cannot be negative.';
    END IF;

    -- Component Payment Validation (No conflicting payment numbers)
    IF v_cash_paid > 0 OR v_upi_paid > 0 THEN
        v_total_paid := v_cash_paid + v_upi_paid;
        IF COALESCE(p_paid_amount, 0) > 0 AND ROUND(p_paid_amount, 2) != v_total_paid THEN
            RAISE EXCEPTION 'Conflicting paid amount (₹%) and split cash/UPI payment total (₹%).', ROUND(p_paid_amount, 2), v_total_paid;
        END IF;
    ELSE
        v_total_paid := ROUND(COALESCE(p_paid_amount, 0.0), 2);
    END IF;

    -- C. CONCURRENCY-SAFE INVOICE NUMBER GENERATION
    v_year := EXTRACT(YEAR FROM NOW());
    v_invoice_num := 'AGM-' || v_year || '-' || LPAD(nextval('invoice_number_seq')::TEXT, 5, '0');

    -- D. VALIDATE FARMER IF SPECIFIED
    IF p_farmer_id IS NOT NULL THEN
        SELECT * INTO v_farmer FROM farmers WHERE id = p_farmer_id FOR UPDATE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Farmer ID % not found', p_farmer_id;
        END IF;
        v_farmer_pending := COALESCE(v_farmer.pending_credit, 0.0);
        v_farmer_limit := COALESCE(v_farmer.credit_limit, 50000.0);
    END IF;

    -- E. PRE-PASS: VALIDATE PRODUCTS, AUTHORITATIVE PRICES, ITEM DISCOUNTS & NET SUBTOTAL BASE
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        v_product_id := (v_item->>'product_id')::BIGINT;
        v_requested_qty := (v_item->>'quantity')::INT;
        v_item_disc := ROUND(COALESCE((v_item->>'discount_amount')::NUMERIC, 0.0), 2);

        IF v_requested_qty IS NULL OR v_requested_qty <= 0 THEN
            RAISE EXCEPTION 'Quantity must be greater than zero for product ID %', v_product_id;
        END IF;

        IF v_item_disc < 0 THEN
            RAISE EXCEPTION 'Item discount cannot be negative for product ID %', v_product_id;
        END IF;

        SELECT * INTO v_product FROM products WHERE id = v_product_id FOR UPDATE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Product ID % not found', v_product_id;
        END IF;

        IF v_product.status != 'Active' THEN
            RAISE EXCEPTION 'Product % is currently inactive and cannot be sold.', v_product.name;
        END IF;

        -- Authoritative price check strictly from DB
        v_unit_price := v_product.selling_price;
        v_item_gross := v_requested_qty * v_unit_price;

        IF v_item_disc > v_item_gross THEN
            RAISE EXCEPTION 'Item discount (₹%) cannot exceed total item gross price (₹%) for product %', v_item_disc, v_item_gross, v_product.name;
        END IF;

        -- Revalidate available non-expired stock from product_batches (Authoritative Stock Source of Truth)
        SELECT COALESCE(SUM(current_quantity), 0) INTO v_available_stock 
        FROM product_batches 
        WHERE product_id = v_product_id 
          AND current_quantity > 0 
          AND (expiry_date IS NULL OR expiry_date >= CURRENT_DATE);

        IF v_available_stock < v_requested_qty THEN
            RAISE EXCEPTION 'Insufficient non-expired stock for product %. Available: %, Requested: %', v_product.name, v_available_stock, v_requested_qty;
        END IF;

        v_gross_subtotal := v_gross_subtotal + v_item_gross;
        v_total_item_discounts := v_total_item_discounts + v_item_disc;
    END LOOP;

    v_net_before_inv_disc_subtotal := v_gross_subtotal - v_total_item_discounts;

    IF v_inv_discount > v_net_before_inv_disc_subtotal THEN
        RAISE EXCEPTION 'Invoice discount (₹%) cannot exceed net subtotal after item discounts (₹%).', v_inv_discount, v_net_before_inv_disc_subtotal;
    END IF;

    v_inv_disc_rem := v_inv_discount;
    v_net_rem := v_net_before_inv_disc_subtotal;

    -- Create Bill header
    INSERT INTO bills (
        invoice_number, farmer_id, farmer_name, farmer_mobile,
        subtotal, taxable_amount, gst_amount, cgst, sgst, igst,
        discount_amount, grand_total, paid_amount, pending_amount,
        payment_method, payment_status, due_date, notes, created_by
    ) VALUES (
        v_invoice_num, p_farmer_id, COALESCE(v_farmer.name, p_farmer_name, 'Walk-in Customer'),
        COALESCE(v_farmer.mobile, p_farmer_mobile), 0, 0, 0, 0, 0, 0,
        0, 0, v_total_paid, 0,
        COALESCE(p_payment_method, 'Cash'), 'Paid', p_due_date, p_notes, v_user_id
    ) RETURNING id INTO v_bill_id;

    -- F. FEFO BATCH ALLOCATION & PROPORTIONAL INVOICE DISCOUNT WITH EXACT RESIDUAL HANDLERS
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        v_product_id := (v_item->>'product_id')::BIGINT;
        v_requested_qty := (v_item->>'quantity')::INT;
        v_item_disc := ROUND(COALESCE((v_item->>'discount_amount')::NUMERIC, 0.0), 2);

        SELECT * INTO v_product FROM products WHERE id = v_product_id;
        v_unit_price := v_product.selling_price;
        v_rem_qty := v_requested_qty;
        v_item_disc_rem := v_item_disc;
        v_item_qty_rem := v_requested_qty;

        -- FEFO Allocation with ROW LOCKING (FOR UPDATE)
        FOR v_batch IN 
            SELECT * FROM product_batches 
            WHERE product_id = v_product_id 
              AND current_quantity > 0 
              AND (expiry_date IS NULL OR expiry_date >= CURRENT_DATE)
            ORDER BY expiry_date ASC NULLS LAST
            FOR UPDATE
        LOOP
            IF v_rem_qty <= 0 THEN EXIT; END IF;

            v_alloc_qty := LEAST(v_batch.current_quantity, v_rem_qty);
            
            -- Deduct stock safely from product_batches
            UPDATE product_batches SET current_quantity = current_quantity - v_alloc_qty WHERE id = v_batch.id;
            v_rem_qty := v_rem_qty - v_alloc_qty;

            -- Record Stock Movement as SALE
            INSERT INTO stock_movements (product_id, batch_id, movement_type, quantity, reference_type, reference_id, notes)
            VALUES (v_product_id, v_batch.id, 'SALE', v_alloc_qty, 'BILL', v_invoice_num, 'FEFO Sale Batch ' || v_batch.batch_number);

            v_item_gross := v_alloc_qty * v_unit_price;

            -- Exact Item Discount Allocation with Residual Handling
            IF v_alloc_qty = v_item_qty_rem THEN
                v_item_disc_alloc := v_item_disc_rem;
            ELSE
                v_item_disc_alloc := ROUND(v_item_disc * (v_alloc_qty::NUMERIC / v_requested_qty::NUMERIC), 2);
                v_item_disc_rem := v_item_disc_rem - v_item_disc_alloc;
                v_item_qty_rem := v_item_qty_rem - v_alloc_qty;
            END IF;

            v_item_net_before_inv := v_item_gross - v_item_disc_alloc;

            -- Exact Invoice Discount Share with Residual Handling
            IF v_net_rem > 0 AND v_item_net_before_inv = v_net_rem THEN
                v_inv_disc_share := v_inv_disc_rem;
            ELSIF v_net_before_inv_disc_subtotal > 0 THEN
                v_inv_disc_share := ROUND(v_inv_discount * (v_item_net_before_inv / v_net_before_inv_disc_subtotal), 2);
                IF v_inv_disc_share > v_inv_disc_rem THEN
                    v_inv_disc_share := v_inv_disc_rem;
                END IF;
                v_inv_disc_rem := v_inv_disc_rem - v_inv_disc_share;
                v_net_rem := v_net_rem - v_item_net_before_inv;
            ELSE
                v_inv_disc_share := 0.0;
            END IF;

            -- Final Taxable Amount after exact item discount & proportional invoice discount
            v_alloc_taxable := v_item_net_before_inv - v_inv_disc_share;
            IF v_alloc_taxable < 0 THEN
                RAISE EXCEPTION 'Taxable amount cannot be negative for product %', v_product.name;
            END IF;

            v_alloc_gst := ROUND(v_alloc_taxable * (v_product.gst_percent / 100.0), 2);
            v_alloc_cgst := ROUND(v_alloc_gst / 2.0, 2);
            v_alloc_sgst := v_alloc_gst - v_alloc_cgst; -- Exact split matching gst_amount
            v_alloc_total := v_alloc_taxable + v_alloc_gst;

            -- Accumulate exact 2-decimal rounded header totals
            v_item_discounts_total := v_item_discounts_total + v_item_disc_alloc;
            v_inv_discounts_total := v_inv_discounts_total + v_inv_disc_share;
            v_taxable_subtotal := v_taxable_subtotal + v_alloc_taxable;
            v_cgst_total := v_cgst_total + v_alloc_cgst;
            v_sgst_total := v_sgst_total + v_alloc_sgst;
            v_gst_total := v_cgst_total + v_sgst_total;
            v_grand_total := v_grand_total + v_alloc_total;

            -- Insert Bill Item with exact snapshot
            INSERT INTO bill_items (
                bill_id, product_id, batch_id, product_name, batch_number, unit, hsn_code,
                quantity, unit_price, rate, gst_percent, discount_amount, taxable_amount,
                gst_amount, cgst, sgst, igst, total_amount
            ) VALUES (
                v_bill_id, v_product_id, v_batch.id, v_product.name, v_batch.batch_number,
                COALESCE(v_product.unit, 'Bags'), COALESCE(v_product.hsn_code, '3105'),
                v_alloc_qty, v_unit_price, v_unit_price, v_product.gst_percent,
                (v_item_disc_alloc + v_inv_disc_share),
                v_alloc_taxable, v_alloc_gst, v_alloc_cgst, v_alloc_sgst, 0.0, v_alloc_total
            );
        END LOOP;

        IF v_rem_qty > 0 THEN
            RAISE EXCEPTION 'Allocation failed: Could not fulfill requested stock for product %', v_product.name;
        END IF;

        -- Update derived total_stock cache on product
        UPDATE products SET total_stock = (
            SELECT COALESCE(SUM(current_quantity), 0) 
            FROM product_batches 
            WHERE product_id = v_product_id 
              AND (expiry_date IS NULL OR expiry_date >= CURRENT_DATE)
        ) WHERE id = v_product_id;

    END LOOP;

    -- G. GRAND TOTAL & CREDIT / DUE DATE VALIDATION
    IF v_total_paid > v_grand_total THEN
        RAISE EXCEPTION 'Paid amount (₹%) cannot exceed grand total (₹%).', v_total_paid, v_grand_total;
    END IF;

    v_pending := GREATEST(0.0, v_grand_total - v_total_paid);

    IF v_pending > 0 THEN
        IF p_farmer_id IS NULL THEN
            RAISE EXCEPTION 'Farmer profile required for credit sales. Anonymous credit sales are not allowed.';
        END IF;

        IF p_due_date IS NULL THEN
            RAISE EXCEPTION 'Due date is required for credit sales.';
        END IF;

        IF (v_farmer_pending + v_pending) > v_farmer_limit THEN
            RAISE EXCEPTION 'Credit limit exceeded for farmer %. Limit: ₹%, Current Pending: ₹%, Requested Credit: ₹%', 
                            v_farmer.name, v_farmer_limit, v_farmer_pending, v_pending;
        END IF;

        v_payment_status := CASE WHEN v_total_paid > 0 THEN 'Partial' ELSE 'Credit' END;
    ELSE
        v_payment_status := 'Paid';
    END IF;

    -- Update Bill Header with exact accumulated totals:
    -- SUM(bill_items.taxable_amount) = bills.taxable_amount
    -- SUM(bill_items.cgst) = bills.cgst
    -- SUM(bill_items.sgst) = bills.sgst
    -- SUM(bill_items.gst_amount) = bills.gst_amount
    -- SUM(bill_items.total_amount) = bills.grand_total
    UPDATE bills SET 
        subtotal = v_gross_subtotal,
        discount_amount = (v_item_discounts_total + v_inv_discounts_total),
        taxable_amount = v_taxable_subtotal,
        gst_amount = v_gst_total,
        cgst = v_cgst_total,
        sgst = v_sgst_total,
        grand_total = v_grand_total,
        pending_amount = v_pending,
        payment_status = v_payment_status
    WHERE id = v_bill_id;

    -- H. RECORD PAYMENTS WITH CONCURRENCY SAFE SEQUENCES AND RECONCILED COMPONENT AMOUNTS
    IF v_cash_paid > 0 THEN
        v_pay_no := 'PAY-' || v_year || '-' || LPAD(nextval('payment_number_seq')::TEXT, 5, '0');
        INSERT INTO payments (payment_number, farmer_id, bill_id, payment_type, amount, payment_method, notes)
        VALUES (v_pay_no, p_farmer_id, v_bill_id, 'BILL_PAYMENT', v_cash_paid, 'Cash', 'Cash Payment on Invoice ' || v_invoice_num);
    END IF;

    IF v_upi_paid > 0 THEN
        v_pay_no := 'PAY-' || v_year || '-' || LPAD(nextval('payment_number_seq')::TEXT, 5, '0');
        INSERT INTO payments (payment_number, farmer_id, bill_id, payment_type, amount, payment_method, notes)
        VALUES (v_pay_no, p_farmer_id, v_bill_id, 'BILL_PAYMENT', v_upi_paid, 'UPI', 'UPI Payment on Invoice ' || v_invoice_num);
    END IF;

    IF v_cash_paid = 0 AND v_upi_paid = 0 AND v_total_paid > 0 THEN
        v_pay_no := 'PAY-' || v_year || '-' || LPAD(nextval('payment_number_seq')::TEXT, 5, '0');
        INSERT INTO payments (payment_number, farmer_id, bill_id, payment_type, amount, payment_method, notes)
        VALUES (v_pay_no, p_farmer_id, v_bill_id, 'BILL_PAYMENT', v_total_paid, COALESCE(p_payment_method, 'Cash'), 'Payment on Invoice ' || v_invoice_num);
    END IF;

    -- I. NULL-SAFE CREDIT LEDGER UPDATE
    IF p_farmer_id IS NOT NULL AND v_pending > 0 THEN
        UPDATE farmers SET pending_credit = COALESCE(pending_credit, 0.0) + v_pending WHERE id = p_farmer_id;
        INSERT INTO credit_transactions (farmer_id, bill_id, transaction_type, amount, balance_after, notes)
        VALUES (p_farmer_id, v_bill_id, 'DEBIT', v_pending, (SELECT pending_credit FROM farmers WHERE id = p_farmer_id), 'Credit sale on Invoice ' || v_invoice_num);
    END IF;

    RETURN jsonb_build_object(
        'id', v_bill_id,
        'invoice_number', v_invoice_num,
        'grand_total', v_grand_total,
        'paid_amount', v_total_paid,
        'pending_amount', v_pending,
        'payment_status', v_payment_status
    );
END;
$$;

