-- 10. SUPPLIER PAYMENT RPC FUNCTION (record_supplier_payment)
CREATE OR REPLACE FUNCTION record_supplier_payment(
    p_supplier_id BIGINT,
    p_amount NUMERIC,
    p_payment_method TEXT,
    p_notes TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_user_id UUID;
    v_supplier suppliers%ROWTYPE;
    v_amount NUMERIC;
    v_pay_no TEXT;
    v_year INT;
    v_new_payable NUMERIC;
BEGIN
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Authentication required to record supplier payment.';
    END IF;

    v_amount := ROUND(COALESCE(p_amount, 0.0), 2);
    IF v_amount <= 0 THEN
        RAISE EXCEPTION 'Payment amount must be greater than zero.';
    END IF;

    SELECT * INTO v_supplier FROM suppliers WHERE id = p_supplier_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Supplier ID % not found.', p_supplier_id;
    END IF;

    IF v_amount > COALESCE(v_supplier.pending_payable, v_supplier.pending_payment, 0.0) THEN
        RAISE EXCEPTION 'Payment amount (₹%) cannot exceed pending payable balance (₹%).', v_amount, COALESCE(v_supplier.pending_payable, v_supplier.pending_payment, 0.0);
    END IF;

    UPDATE suppliers SET
        pending_payment = GREATEST(0.0, COALESCE(pending_payment, 0.0) - v_amount),
        pending_payable = GREATEST(0.0, COALESCE(pending_payable, 0.0) - v_amount)
    WHERE id = p_supplier_id
    RETURNING COALESCE(pending_payable, pending_payment, 0.0) INTO v_new_payable;

    v_year := EXTRACT(YEAR FROM NOW());
    v_pay_no := 'PAY-SUP-' || v_year || '-' || LPAD(nextval('payment_number_seq')::TEXT, 5, '0');

    INSERT INTO payments (payment_number, supplier_id, payment_type, amount, payment_method, notes)
    VALUES (v_pay_no, p_supplier_id, 'SUPPLIER_PAYMENT', v_amount, COALESCE(p_payment_method, 'Bank Transfer'), COALESCE(p_notes, 'Supplier balance payment'));

    RETURN jsonb_build_object(
        'supplier_id', p_supplier_id,
        'payment_number', v_pay_no,
        'amount_paid', v_amount,
        'remaining_payable', v_new_payable
    );
END;
$$;

REVOKE EXECUTE ON FUNCTION record_supplier_payment(BIGINT, NUMERIC, TEXT, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION record_supplier_payment(BIGINT, NUMERIC, TEXT, TEXT) TO authenticated;


-- 11. FARMER CREDIT PAYMENT RPC FUNCTION (record_farmer_payment)
CREATE OR REPLACE FUNCTION record_farmer_payment(
    p_farmer_id BIGINT,
    p_amount NUMERIC,
    p_payment_method TEXT,
    p_notes TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_user_id UUID;
    v_farmer farmers%ROWTYPE;
    v_amount NUMERIC;
    v_pay_no TEXT;
    v_payment_id BIGINT;
    v_year INT;
    v_new_pending NUMERIC;
    v_rem_payment NUMERIC;
    v_bill RECORD;
    v_alloc NUMERIC;
    v_new_bill_paid NUMERIC;
    v_new_bill_pending NUMERIC;
    v_new_bill_status TEXT;
BEGIN
    -- 1. AUTHENTICATION CHECK
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Authentication required to record farmer payment.';
    END IF;

    -- 2. VALIDATE AMOUNT
    v_amount := ROUND(COALESCE(p_amount, 0.0), 2);
    IF v_amount <= 0 THEN
        RAISE EXCEPTION 'Payment amount must be greater than zero.';
    END IF;

    -- 3. LOCK FARMER ROW & VALIDATE
    SELECT * INTO v_farmer FROM farmers WHERE id = p_farmer_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Farmer ID % not found.', p_farmer_id;
    END IF;

    IF v_amount > COALESCE(v_farmer.pending_credit, 0.0) THEN
        RAISE EXCEPTION 'Payment amount (₹%) cannot exceed farmer pending credit (₹%).', v_amount, COALESCE(v_farmer.pending_credit, 0.0);
    END IF;

    -- 4. CALCULATE NEW PENDING CREDIT
    v_new_pending := GREATEST(0.0, COALESCE(v_farmer.pending_credit, 0.0) - v_amount);

    -- 5. GENERATE CONCURRENCY-SAFE PAYMENT NUMBER
    v_year := EXTRACT(YEAR FROM NOW());
    v_pay_no := 'PAY-FMR-' || v_year || '-' || LPAD(nextval('payment_number_seq')::TEXT, 5, '0');

    -- 6. CREATE PAYMENT RECORD
    INSERT INTO payments (
        payment_number, farmer_id, payment_type, amount, payment_method, notes, created_at
    ) VALUES (
        v_pay_no, p_farmer_id, 'FARMER_CREDIT_REPAYMENT', v_amount, COALESCE(p_payment_method, 'Cash'), COALESCE(p_notes, 'Farmer credit repayment'), NOW()
    ) RETURNING id INTO v_payment_id;

    -- 7. REDUCE FARMER PENDING CREDIT
    UPDATE farmers SET pending_credit = v_new_pending WHERE id = p_farmer_id;

    -- 8. CREATE CREDIT TRANSACTION RECORD
    INSERT INTO credit_transactions (
        farmer_id, payment_id, transaction_type, amount, balance_after, notes, created_at
    ) VALUES (
        p_farmer_id, v_payment_id, 'CREDIT', v_amount, v_new_pending, COALESCE(p_notes, 'Repayment on Receipt ' || v_pay_no), NOW()
    );

    -- 9. FIFO PAYMENT ALLOCATION TO OLDEST PENDING BILLS
    v_rem_payment := v_amount;
    FOR v_bill IN 
        SELECT id, paid_amount, pending_amount, grand_total 
        FROM bills 
        WHERE farmer_id = p_farmer_id AND pending_amount > 0 
        ORDER BY created_at ASC, id ASC 
        FOR UPDATE
    LOOP
        EXIT WHEN v_rem_payment <= 0;

        v_alloc := LEAST(v_rem_payment, v_bill.pending_amount);
        v_new_bill_paid := v_bill.paid_amount + v_alloc;
        v_new_bill_pending := GREATEST(0.0, v_bill.pending_amount - v_alloc);
        v_new_bill_status := CASE WHEN v_new_bill_pending = 0 THEN 'Paid' ELSE 'Partial' END;

        UPDATE bills SET 
            paid_amount = v_new_bill_paid,
            pending_amount = v_new_bill_pending,
            payment_status = v_new_bill_status
        WHERE id = v_bill.id;

        v_rem_payment := v_rem_payment - v_alloc;
    END LOOP;

    RETURN jsonb_build_object(
        'farmer_id', p_farmer_id,
        'payment_number', v_pay_no,
        'amount_paid', v_amount,
        'remaining_pending_credit', v_new_pending
    );
END;
$$;

REVOKE EXECUTE ON FUNCTION record_farmer_payment(BIGINT, NUMERIC, TEXT, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION record_farmer_payment(BIGINT, NUMERIC, TEXT, TEXT) TO authenticated;

