-- Farmers (RESTRICT deletion if credit transactions exist; NOT NULL Credit Defaults)
CREATE TABLE IF NOT EXISTS farmers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_code TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    mobile TEXT UNIQUE NOT NULL,
    village TEXT,
    district TEXT,
    land_acreage NUMERIC(10, 2) NOT NULL DEFAULT 0.0 CHECK (land_acreage >= 0),
    primary_crop TEXT,
    pending_credit NUMERIC(12, 2) NOT NULL DEFAULT 0.0 CHECK (pending_credit >= 0),
    credit_limit NUMERIC(12, 2) NOT NULL DEFAULT 50000.0 CHECK (credit_limit >= 0),
    status TEXT DEFAULT 'Active',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

